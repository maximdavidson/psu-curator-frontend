export function getDepartmentsForFaculty(faculty: string): string[] {
  const entry = UNIVERSITY_STRUCTURE.find(
    (f) => f.name.toLowerCase() === faculty.trim().toLowerCase()
  );
  return entry?.departments ?? [];
}
